import { AnalysisResult } from '../types/growth';

export function generateMarkdownReport(result: AnalysisResult): string {
  const { input, metrics, diagnosis, experiments, timestamp, mode } = result;
  const formattedDate = new Date(timestamp).toLocaleString('en-US', {
    dateStyle: 'long',
    timeStyle: 'short',
  });

  return `# LaunchPilot AI — Growth Diagnostic Report
**"Diagnosis before marketing: Fix the leaky bucket before buying more water."**

---

### 1. Startup Overview
- **Product Name:** ${input.productName}
- **Target Audience:** ${input.targetAudience}
- **Product Description:** ${input.productDescription}
${input.websiteUrl ? `- **Website URL:** ${input.websiteUrl}` : ''}
${input.growthChallenge ? `- **Stated Growth Challenge:** ${input.growthChallenge}` : ''}
- **Analysis Date:** ${formattedDate}
- **Analysis Mode:** ${mode === 'nebius_enhanced' ? 'NVIDIA Nemotron (Nebius Token Factory)' : 'Deterministic Growth Diagnostics (Rule-Based)'}

---

### 2. Funnel Conversion Metrics
| Funnel Stage | Volume | Stage Conversion Rate | Stage Drop-off |
| :--- | :--- | :--- | :--- |
| **Top of Funnel (Visitors)** | ${metrics.visitors.toLocaleString()} | 100% (Baseline) | — |
| **Registration (Signups)** | ${metrics.signups.toLocaleString()} | **${metrics.signupRate}%** (Visitor → Signup) | ${metrics.visitorToSignupDropoff}% drop-off |
| **Value Milestone (Activated)** | ${metrics.activated.toLocaleString()} | **${metrics.activationRate}%** (Signup → Activated) | ${metrics.signupToActivationDropoff}% drop-off |
| **Habit Formation (Returning)** | ${metrics.returning.toLocaleString()} | **${metrics.retentionProxyRate}%** (Activated → Returning proxy) | ${metrics.activationToRetentionDropoff}% drop-off |

*Note on Retention Proxy: This calculation reflects returning users divided by activated users in the analyzed sample, not a longitudinal cohort tracking curve.*

---

### 3. Growth Diagnosis: ${diagnosis.stageName.toUpperCase()}
**Finding:** ${diagnosis.headline}

**Executive Summary:**
${diagnosis.summary}

#### Factual Observed Evidence:
${diagnosis.observedEvidence.map((e) => `- ${e}`).join('\n')}

#### Plausible Hypotheses (Root Causes to Investigate):
${diagnosis.possibleCauses.map((c) => `- ${c}`).join('\n')}

#### Important Diagnostic Context & Caveats:
${diagnosis.caveatsAndWarnings.map((w) => `- ${w}`).join('\n')}
- **Industry Context:** ${diagnosis.benchmarkContext}

#### Recommended Qualitative Discovery:
> ${diagnosis.recommendedDiscovery}

---

### 4. Prescribed Measurable Experiments
We recommend running exactly one or two focused micro-experiments before spending capital on promotion.

#### Experiment 1: ${experiments[0].title}
- **Target Stage:** ${experiments[0].stage}
- **Hypothesis:** ${experiments[0].hypothesis}
- **Why Worth Testing:** ${experiments[0].whyWorthTesting}
- **Execution Steps:**
  1. ${experiments[0].executionSteps[0]}
  2. ${experiments[0].executionSteps[1]}
  3. ${experiments[0].executionSteps[2]}
- **Primary Success Metric:** ${experiments[0].primarySuccessMetric}
- **Suggested Testing Window:** ${experiments[0].suggestedPeriod}
- **Validation Signal:** ${experiments[0].expectedSignal}

#### Experiment 2: ${experiments[1].title}
- **Target Stage:** ${experiments[1].stage}
- **Hypothesis:** ${experiments[1].hypothesis}
- **Why Worth Testing:** ${experiments[1].whyWorthTesting}
- **Execution Steps:**
  1. ${experiments[1].executionSteps[0]}
  2. ${experiments[1].executionSteps[1]}
  3. ${experiments[1].executionSteps[2]}
- **Primary Success Metric:** ${experiments[1].primarySuccessMetric}
- **Suggested Testing Window:** ${experiments[1].suggestedPeriod}
- **Validation Signal:** ${experiments[1].expectedSignal}

---

### 5. Next 48 Hours Action Checklist
1. **Verify tracking fidelity:** Ensure the event marking "Activated User" represents genuine first-value creation, not just viewing a dashboard.
2. **Conduct 5 qualitative user discovery calls:** Talk directly to users who dropped off at the diagnosed stage.
3. **Deploy Experiment 1:** Implement the minimal test version without over-engineering.
4. **Hold promotion budget:** Do not scale paid advertising until conversion through this bottleneck reaches healthy baselines.

---
*Report generated by LaunchPilot AI — Growth Doctor.*
`;
}

export function downloadReportAsFile(result: AnalysisResult): void {
  const markdown = generateMarkdownReport(result);
  const blob = new Blob([markdown], { type: 'text/markdown;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const safeName = (result.input.productName || 'startup')
    .toLowerCase()
    .replace(/[^a-z0-9_-]/g, '_');
  const filename = `LaunchPilot_Growth_Report_${safeName}.md`;

  const link = document.createElement('a');
  link.href = url;
  link.setAttribute('download', filename);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
